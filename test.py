# You are given a number with multiple digits. Construct the 
# largest possible number using exactly those digits.
# Sample:
# Input: 310204
# Output: 432100

def largest_from_digits(n: int) -> int:
    s = str(abs(n))
    digits = sorted(s)

    if n >= 0:
        return int("".join(sorted(s, reverse=True)))

    # n < 0: make smallest number (no leading zeros)
    if digits[0] == '0':
        j = 0
        while j < len(digits) and digits[j] == '0':
            j += 1
        # put first non-zero in front, then zeros, then the rest
        digits[0], digits[j] = digits[j], digits[0]

    return -int("".join(digits))


