workshops = [(2020, 3), (2020, 2), (2021, 4), (2023, 10), (2024, 1)]


def max_classes(workshops):
    
    years_total = dict()
    for y,c in workshops:
        years_total[y] = years_total.get(y,0) + c
    
    sorted_years = sorted(years_total.keys())
    
    max_classes = years_total[sorted_years[0]]
    run_sum = years_total[sorted_years[0]]
    
    for i in range(1,len(sorted_years)):
        if sorted_years[i] != sorted_years[i-1] + 1:
            run_sum = years_total[sorted_years[i]]
        
        else:
            run_sum += years_total[sorted_years[i]]
        max_classes = max(max_classes,run_sum)
    return max_classes
print(max_classes(workshops))
        
