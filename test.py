# Given a dictionary where each key maps to a list of words, 
# return the word that appears the most across all lists. 
# If there’s a tie, return any one.

# Sample:

# Input: {"a": ["cat", "dog", "cat"], "b": ["dog", "bird"], "c": ["cat"]}

# Output: "cat"

d = {"a": ["cat", "dog", "cat"], "b": ["dog", "bird"], "c": ["cat"]}

def common_word(d):

    if not d: return None

    freq = dict()
    best_count = 0
    best_word = None

    for val in d.values():
        for v in val:
            freq[v] = freq.get(v,0) + 1
            if freq[v] > best_count:
                best_count = freq[v]
                best_word = v
    return best_word


print(common_word(d))


